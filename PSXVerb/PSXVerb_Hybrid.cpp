// Block size
constexpr size_t kBlockSize = 16;

// Parameter smoothing
struct ParamSmoother {
    float value = 0.0f;
    float coeff = 0.05f;

    void Init(float v) { value = v; }
    float Process(float target) {
        value += coeff * (target - value);
        return value;
    }
};

ParamSmoother smMix;

// Audio callback counter
static volatile uint32_t audio_callback_count = 0;

// Audio callback - OPTIMIZED for minimal latency
void AudioCallback(AudioHandle::InputBuffer in,
                   AudioHandle::OutputBuffer out,
                   size_t size)
{
    audio_callback_count++;

    // Always copy dry (zero latency)
    float dry_L[kBlockSize];
    float dry_R[kBlockSize];

    for (size_t i = 0; i < size; ++i) {
        dry_L[i] = in[0][i];
        dry_R[i] = in[1][i];
    }

    if (!reverb_ready_ || bypass_) {
        // Bypass - just output dry
        for (size_t i = 0; i < size; ++i) {
            out[0][i] = dry_L[i];
            out[1][i] = dry_R[i];
        }
        return;
    }

    // Process reverb
    float early_L[kBlockSize];
    float early_R[kBlockSize];
    float tail_L[kBlockSize];
    float tail_R[kBlockSize];

    // Early reflections (FIR - true IR)
    fir.ProcessBlock(in[0], in[1], early_L, early_R, size);

    // Tail reverb (algorithmic, fitted to IR)
    tail.ProcessBlock(in[0], in[1], tail_L, tail_R, size);

    // Mix
    float mix = smMix.value;
    for (size_t i = 0; i < size; ++i) {
        float wet_L = early_L[i] + tail_L[i];
        float wet_R = early_R[i] + tail_R[i];

        out[0][i] = dry_L[i] * (1.0f - mix) + wet_L * mix;
        out[1][i] = dry_R[i] * (1.0f - mix) + wet_R * mix;
    }
}

void InitReverb(int ir_index)
{
    if (ir_index < 0 || ir_index >= 4) ir_index = 0;
    current_ir_index_ = ir_index;
    profiles[ir_index] = PrecomputedProfiles::kProfiles[ir_index];
    const float* src_taps = &PrecomputedProfiles::g_AllTaps[ir_index * 1116];
    std::memcpy(profiles[ir_index].taps, src_taps, 1116 * sizeof(float));
    fir.Reset();
    fir.Init(profiles[ir_index].taps, profiles[ir_index].N_taps);
    tail.Init(sample_rate_);
    tail.SetFromProfile(profiles[ir_index]);
}

